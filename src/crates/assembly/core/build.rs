fn main() {
    if std::env::var_os("CARGO_FEATURE_AGENT_RUNTIME").is_some() {
        emit_rerun_if_changed(std::path::Path::new("builtin_skills"));
        if let Err(e) = build_embedded_builtin_skills_metadata() {
            eprintln!("Warning: Failed to embed built-in skills metadata: {}", e);
        }
    }
}

fn build_embedded_builtin_skills_metadata() -> Result<(), Box<dyn std::error::Error>> {
    use sha2::{Digest, Sha256};
    use std::fs;
    use std::io::Write;
    use std::path::{Path, PathBuf};

    fn collect_files(root: &Path, current: &Path, out: &mut Vec<PathBuf>) -> std::io::Result<()> {
        for entry in fs::read_dir(current)? {
            let entry = entry?;
            let path = entry.path();
            if path.is_dir() {
                collect_files(root, &path, out)?;
            } else if path.is_file() {
                out.push(path.strip_prefix(root).unwrap_or(&path).to_path_buf());
            }
        }

        Ok(())
    }

    let manifest_dir = std::env::var("CARGO_MANIFEST_DIR")?;
    let builtin_root = Path::new(&manifest_dir).join("builtin_skills");

    println!("cargo:rerun-if-changed={}", builtin_root.display());
    emit_rerun_if_changed(&builtin_root);

    let mut files = Vec::new();
    if builtin_root.exists() {
        collect_files(&builtin_root, &builtin_root, &mut files)?;
    }
    files.sort();

    let mut hasher = Sha256::new();
    for relative_path in files {
        let normalized = relative_path.to_string_lossy().replace('\\', "/");
        hasher.update(normalized.as_bytes());
        hasher.update([0]);
        hasher.update(fs::read(builtin_root.join(&relative_path))?);
        hasher.update([0xff]);
    }
    let bundle_hash = format!("{:x}", hasher.finalize());

    let out_dir = std::env::var("OUT_DIR")?;
    let dest_path = Path::new(&out_dir).join("embedded_builtin_skills.rs");
    let mut file = fs::File::create(&dest_path)?;

    writeln!(
        file,
        "// Embedded built-in skills metadata (auto-generated by build.rs)"
    )?;
    writeln!(file, "// Do not edit manually.")?;
    writeln!(
        file,
        "pub const BUILTIN_SKILLS_BUNDLE_HASH: &str = \"{}\";",
        bundle_hash
    )?;

    Ok(())
}

fn emit_rerun_if_changed(path: &std::path::Path) {
    if !path.exists() {
        return;
    }

    println!("cargo:rerun-if-changed={}", path.display());

    if path.is_dir() {
        let entries = match std::fs::read_dir(path) {
            Ok(entries) => entries,
            Err(_) => return,
        };

        for entry in entries.flatten() {
            emit_rerun_if_changed(&entry.path());
        }
    }
}
