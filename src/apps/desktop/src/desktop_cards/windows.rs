//! Native windows for desktop cards: one transparent, frameless window per card.

use openbitfun_core::agentic::tools::desktop_card_host::{
    clamp_size, DesktopCardPosition, DesktopCardRecord, DesktopCardSize, DESKTOP_CARD_MAX_HEIGHT,
    DESKTOP_CARD_MAX_WIDTH, DESKTOP_CARD_MIN_HEIGHT, DESKTOP_CARD_MIN_WIDTH,
};
use tauri::Manager;

pub const DESKTOP_CARD_WINDOW_PREFIX: &str = "desktop-card-";
const EDGE_MARGIN: f64 = 24.0;
const CASCADE_STEP: f64 = 28.0;

pub(crate) fn window_label(card_id: &str) -> String {
    format!("{DESKTOP_CARD_WINDOW_PREFIX}{card_id}")
}

pub(crate) fn card_id_from_label(label: &str) -> Option<&str> {
    label.strip_prefix(DESKTOP_CARD_WINDOW_PREFIX)
}

/// Card ids are generated by the host; reject anything that could escape the
/// window label or the URL query.
pub(crate) fn is_valid_card_id(card_id: &str) -> bool {
    !card_id.is_empty()
        && card_id.len() <= 64
        && card_id
            .chars()
            .all(|ch| ch.is_ascii_alphanumeric() || ch == '-' || ch == '_')
}

pub(crate) fn card_size(card: &DesktopCardRecord) -> DesktopCardSize {
    let size = card.size.unwrap_or_else(|| {
        card.template
            .known()
            .map(|template| template.default_size())
            .unwrap_or(DesktopCardSize {
                width: 280.0,
                height: 180.0,
            })
    });
    clamp_size(size)
}

#[derive(Debug, Clone, Copy)]
struct WorkArea {
    x: f64,
    y: f64,
    width: f64,
    height: f64,
}

fn work_areas(app: &tauri::AppHandle) -> Vec<WorkArea> {
    app.available_monitors()
        .unwrap_or_default()
        .into_iter()
        .map(|monitor| {
            let scale = monitor.scale_factor();
            let area = monitor.work_area();
            let position = area.position.to_logical::<f64>(scale);
            let size = area.size.to_logical::<f64>(scale);
            WorkArea {
                x: position.x,
                y: position.y,
                width: size.width,
                height: size.height,
            }
        })
        .collect()
}

fn primary_work_area(app: &tauri::AppHandle) -> Option<WorkArea> {
    let monitor = app.primary_monitor().ok().flatten()?;
    let scale = monitor.scale_factor();
    let area = monitor.work_area();
    let position = area.position.to_logical::<f64>(scale);
    let size = area.size.to_logical::<f64>(scale);
    Some(WorkArea {
        x: position.x,
        y: position.y,
        width: size.width,
        height: size.height,
    })
}

/// A saved position stays valid only while enough of the card remains on a
/// connected display; otherwise the card would be restored off screen.
fn visible_on_some_display(
    areas: &[WorkArea],
    position: DesktopCardPosition,
    size: DesktopCardSize,
) -> bool {
    const MIN_VISIBLE: f64 = 48.0;
    areas.iter().any(|area| {
        let overlap_x = (position.x + size.width).min(area.x + area.width) - position.x.max(area.x);
        let overlap_y =
            (position.y + size.height).min(area.y + area.height) - position.y.max(area.y);
        overlap_x >= MIN_VISIBLE && overlap_y >= MIN_VISIBLE
    })
}

pub(crate) fn default_position(
    app: &tauri::AppHandle,
    size: DesktopCardSize,
    cascade_index: usize,
) -> Option<DesktopCardPosition> {
    let area = primary_work_area(app).or_else(|| work_areas(app).into_iter().next())?;
    let max_steps = ((area.height / 2.0) / CASCADE_STEP).max(1.0) as usize;
    let offset = (cascade_index % max_steps) as f64 * CASCADE_STEP;
    Some(DesktopCardPosition {
        x: (area.x + area.width - size.width - EDGE_MARGIN - offset).max(area.x),
        y: area.y + EDGE_MARGIN + offset,
    })
}

pub(crate) fn resolve_position(
    app: &tauri::AppHandle,
    card: &DesktopCardRecord,
    cascade_index: usize,
) -> Option<DesktopCardPosition> {
    let size = card_size(card);
    match card.position {
        Some(position)
            if position.x.is_finite()
                && position.y.is_finite()
                && visible_on_some_display(&work_areas(app), position, size) =>
        {
            Some(position)
        }
        _ => default_position(app, size, cascade_index),
    }
}

/// Desktop-only presentation metadata lives in the record's forward-compatible
/// extension map, not in the portable Agent tool's configuration contract.
pub(crate) fn desktop_pinned(card: &DesktopCardRecord) -> bool {
    !card.always_on_top
        && card
            .extra
            .get("desktopPinned")
            .and_then(serde_json::Value::as_bool)
            == Some(true)
}

pub(crate) async fn open_window(
    app: &tauri::AppHandle,
    card: &DesktopCardRecord,
    position: Option<DesktopCardPosition>,
) -> Result<(), String> {
    if !is_valid_card_id(&card.id) {
        return Err(format!("Invalid desktop card id: {}", card.id));
    }
    let label = window_label(&card.id);
    if let Some(window) = app.get_webview_window(&label) {
        apply_stacking(app, &card.id, card.always_on_top, desktop_pinned(card)).await?;
        if let Err(error) = window.unminimize() {
            log::debug!(
                "Failed to unminimize desktop card window: card_id={}, error={}",
                card.id,
                error
            );
        }
        return window
            .show()
            .map_err(|error| format!("Failed to show desktop card window: {error}"));
    }

    let size = card_size(card);
    let url = crate::appearance::app_url(
        app,
        &format!("?openbitfunWindow=desktop-card&cardId={}", card.id),
    );
    let mut builder = tauri::WebviewWindowBuilder::new(app, &label, url)
        .title(format!("OpenBitFun Card - {}", card.title))
        .inner_size(size.width, size.height)
        .min_inner_size(DESKTOP_CARD_MIN_WIDTH, DESKTOP_CARD_MIN_HEIGHT)
        .max_inner_size(DESKTOP_CARD_MAX_WIDTH, DESKTOP_CARD_MAX_HEIGHT)
        .resizable(true)
        .decorations(false)
        .transparent(true)
        .always_on_top(card.always_on_top)
        .skip_taskbar(true)
        .shadow(false)
        .visible(false)
        .focused(false)
        .accept_first_mouse(true)
        .background_color(tauri::window::Color(0, 0, 0, 0))
        .disable_drag_drop_handler();
    if let Some(position) = position {
        builder = builder.position(position.x, position.y);
    }
    let window = builder
        .build()
        .map_err(|error| format!("Failed to create desktop card window: {error}"))?;
    if let Err(error) =
        apply_stacking(app, &card.id, card.always_on_top, desktop_pinned(card)).await
    {
        let _ = window.destroy();
        return Err(error);
    }
    window
        .show()
        .map_err(|error| format!("Failed to show desktop card window: {error}"))
}

pub(crate) fn close_window(app: &tauri::AppHandle, card_id: &str) {
    if let Some(window) = app.get_webview_window(&window_label(card_id)) {
        if let Err(error) = window.destroy() {
            log::warn!(
                "Failed to destroy desktop card window: card_id={}, error={}",
                card_id,
                error
            );
        }
    }
}

pub(crate) fn apply_window_size(app: &tauri::AppHandle, card_id: &str, size: DesktopCardSize) {
    if let Some(window) = app.get_webview_window(&window_label(card_id)) {
        if let Err(error) = window.set_size(tauri::LogicalSize::new(size.width, size.height)) {
            log::warn!(
                "Failed to resize desktop card window: card_id={}, error={}",
                card_id,
                error
            );
        }
    }
}

pub(crate) async fn apply_stacking(
    app: &tauri::AppHandle,
    card_id: &str,
    always_on_top: bool,
    desktop_pinned: bool,
) -> Result<(), String> {
    if desktop_pinned && !cfg!(windows) {
        return Err("Pinning cards to the desktop is supported only on Windows.".to_string());
    }
    let Some(window) = app.get_webview_window(&window_label(card_id)) else {
        return Ok(()); // Hidden cards apply the saved mode when shown.
    };
    #[cfg(windows)]
    {
        let native_window = window.clone();
        let (send, receive) = tokio::sync::oneshot::channel();
        window
            .run_on_main_thread(move || {
                let result = native_window
                    .hwnd()
                    .map_err(|error| error.to_string())
                    .and_then(|hwnd| super::desktop_layer::set_pinned(hwnd, desktop_pinned));
                let _ = send.send(result);
            })
            .map_err(|error| error.to_string())?;
        receive.await.map_err(|error| error.to_string())??;
    }
    // Parenting removes topmost before attaching; never promote a child window
    // back into the global topmost band through Tauri's top-level setter.
    if !desktop_pinned {
        window
            .set_always_on_top(always_on_top)
            .map_err(|error| error.to_string())?;
    }
    Ok(())
}

pub(crate) fn bring_to_front(app: &tauri::AppHandle, card_id: &str) {
    if let Some(window) = app.get_webview_window(&window_label(card_id)) {
        let _ = window.unminimize();
        let _ = window.show();
        if let Err(error) = window.set_focus() {
            log::debug!(
                "Failed to focus desktop card window: card_id={}, error={}",
                card_id,
                error
            );
        }
    }
}

pub(crate) fn open_card_labels(app: &tauri::AppHandle) -> Vec<String> {
    app.webview_windows()
        .into_keys()
        .filter(|label| label.starts_with(DESKTOP_CARD_WINDOW_PREFIX))
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn card_ids_are_restricted_to_label_safe_characters() {
        assert!(is_valid_card_id("card-1a2b_3"));
        assert!(!is_valid_card_id(""));
        assert!(!is_valid_card_id("a/b"));
        assert!(!is_valid_card_id("a&cardId=b"));
        assert_eq!(card_id_from_label(&window_label("abc")), Some("abc"));
    }

    #[test]
    fn saved_positions_off_every_display_are_rejected() {
        let areas = [WorkArea {
            x: 0.0,
            y: 0.0,
            width: 1440.0,
            height: 900.0,
        }];
        let size = DesktopCardSize {
            width: 280.0,
            height: 160.0,
        };
        assert!(visible_on_some_display(
            &areas,
            DesktopCardPosition { x: 100.0, y: 100.0 },
            size
        ));
        assert!(!visible_on_some_display(
            &areas,
            DesktopCardPosition {
                x: 3000.0,
                y: 100.0
            },
            size
        ));
        assert!(!visible_on_some_display(
            &areas,
            DesktopCardPosition { x: 1420.0, y: 0.0 },
            size
        ));
    }
}
