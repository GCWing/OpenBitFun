#!/usr/bin/env node
/** Bundle the public design-system CSS for the offline, static Data Tools UI. */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(import.meta.dirname, '..');
const OUTPUT = join(ROOT, 'src/apps/data-tools/ui/generated/design-system.css');
const themeRequire = createRequire(join(ROOT, 'design-system/packages/theme-openbitfun/package.json'));

function bundleStylesheet(file, ancestors = new Set()) {
  if (ancestors.has(file)) throw new Error(`Circular design-system stylesheet import: ${file}`);
  const imports = new Set([...ancestors, file]);
  const requireFromFile = createRequire(file);
  return readFileSync(file, 'utf8').replace(/\r\n?/g, '\n').replace(
    /@import\s+["']([^"']+)["'];/g,
    (_, specifier) => bundleStylesheet(requireFromFile.resolve(specifier), imports).trimEnd(),
  );
}

export async function generateDataToolsTheme({ check = false } = {}) {
  // Build the owning packages before reading their exports; an older dist must
  // never make a source change appear current in the generated-output check.
  await import('../design-system/packages/design-tokens/scripts/build.mjs');
  await import('../design-system/packages/theme-openbitfun/scripts/build.mjs');
  const css = bundleStylesheet(themeRequire.resolve('@openbitfun/theme-openbitfun/default.css'));
  if (/@import\b|url\(/i.test(css)) {
    throw new Error('Data Tools design-system CSS must have no external asset dependencies.');
  }
  const content = '/* Generated by scripts/generate-data-tools-theme.mjs. Do not edit. */\n'
    + `${css.trimEnd()}\n`;
  const current = existsSync(OUTPUT) ? readFileSync(OUTPUT, 'utf8').replace(/\r\n?/g, '\n') : null;
  if (current === content) return;
  if (check) {
    throw new Error('Data Tools theme is stale. Run `pnpm run data-tools:theme:generate`.');
  }
  mkdirSync(dirname(OUTPUT), { recursive: true });
  writeFileSync(OUTPUT, content, 'utf8');
  console.log('[data-tools] Generated offline design-system CSS');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  generateDataToolsTheme({ check: process.argv.includes('--check') }).catch((error) => {
    console.error(error.message);
    process.exitCode = 1;
  });
}
