function resolveOwnerFacts(source) {
  const resolved = structuredClone(source);
  const ownerDefinitions = loadOwnerDefinitions();
  const ownerById = new Map();
  for (const definition of ownerDefinitions) {
    const memberId = definition.kind === 'option' ? definition.optionId : definition.operationId;
    const id = `${definition.capabilityId}:${definition.kind}:${memberId}`;
    if (!definition.capabilityId || !memberId || !['option', 'operation'].includes(definition.kind)) {
      throw new Error(`Compiled ProductControl owner registry has an invalid definition: ${id}`);
    }
    if (ownerById.has(id)) throw new Error(`Duplicate compiled ProductControl owner definition: ${id}`);
    ownerById.set(id, definition);
  }

  for (const capability of resolved.capabilities) {
    capability.options = (capability.options ?? []).map((overlay) => {
      const id = `${capability.id}:option:${overlay.id}`;
      const owner = ownerById.get(id);
      if (!owner) throw new Error(`ProductControl option overlay has no compiled owner: ${id}`);
      for (const forbidden of ['handler', 'valueSchema']) {
        if (Object.hasOwn(overlay, forbidden)) {
          throw new Error(`${id}.${forbidden} is executable owner data and may not be handwritten in the manual overlay`);
        }
      }
      ownerById.delete(id);
      return { ...overlay, valueSchema: owner.valueSchema, handler: owner.handler };
    });
    capability.operations = (capability.operations ?? []).map((overlay) => {
      const id = `${capability.id}:operation:${overlay.id}`;
      const owner = ownerById.get(id);
      if (!owner) throw new Error(`ProductControl operation overlay has no compiled owner: ${id}`);
      for (const forbidden of ['risk', 'inputSchema', 'argumentScopes', 'handler']) {
        if (Object.hasOwn(overlay, forbidden)) {
          throw new Error(`${id}.${forbidden} is executable owner data and may not be handwritten in the manual overlay`);
        }
      }
      ownerById.delete(id);
      return {
        ...overlay,
        risk: owner.risk,
        inputSchema: owner.inputSchema,
        argumentScopes: owner.argumentScopes,
        handler: owner.handler,
      };
    });
  }
  if (ownerById.size) {
    throw new Error(
      `Compiled ProductControl definitions missing explanatory overlays: ${[...ownerById.keys()].sort().join(', ')}`,
    );
  }

  const appearance = resolved.capabilities.find(({ id }) => id === 'setting.application.appearance');
  if (!appearance) throw new Error('Appearance capability is required by the product-control plane');
  const theme = appearance.options?.find(({ id }) => id === 'theme');
  const language = appearance.options?.find(({ id }) => id === 'language');
  if (theme?.handler?.kind !== 'appearanceSelection' || language?.handler?.kind !== 'language') {
    throw new Error('Appearance theme and language must retain their typed owner bindings');
  }

  const appearanceContract = JSON.parse(readFileSync(APPEARANCE_BOOTSTRAP_PATH, 'utf8'));
  const appearanceIds = appearanceContract.appearances?.map(({ id }) => id) ?? [];
  if (!appearanceIds.length || appearanceIds.some((id) => typeof id !== 'string' || !id.trim())) {
    throw new Error('Startup appearance contract did not expose valid built-in appearance IDs');
  }
  theme.valueSchema.enum = ['system', ...appearanceIds];

  const localeContract = JSON.parse(readFileSync(LOCALE_CONTRACT_PATH, 'utf8'));
  const localeIds = localeContract.locales?.map(({ id }) => id) ?? [];
  if (!localeIds.length || localeIds.some((id) => typeof id !== 'string' || !id.trim())) {
    throw new Error('Locale contract did not expose valid locale IDs');
  }
  language.valueSchema.enum = localeIds;
  return resolved;
}

function availability(available, reason, requiredCapabilities = []) {
  const result = available ? { available: true } : { available: false, reason };
  if (requiredCapabilities.length) result.requiredCapabilities = requiredCapabilities;
  return result;
}

function definitionAvailability(kind, handler) {
  const desktop = availability(true);
  const peer = (...requiredCapabilities) => availability(
    true,
    undefined,
    ['product_control_v1', ...requiredCapabilities],
  );
  const remote = availability(true);
  if (kind === 'query' || kind === 'delegate') {
    return {
      desktop,
      cli: availability(true),
      peer: peer(),
      remoteControl: remote,
      detachedDispatch: availability(true),
    };
  }
  if (kind === 'open') {
    const reason = 'This delivery profile has no live presentation surface';
    return {
      desktop,
      cli: availability(false, reason),
      peer: peer('product_control_presentation_v1'),
      remoteControl: remote,
      detachedDispatch: availability(false, reason),
    };
  }
  const presentationOnly = handler?.kind === 'productAction';
  const nativeProvider = handler?.kind === 'provider';
  const headlessReason = presentationOnly
    ? 'This command requires a live presentation surface'
    : 'This command requires a native product-host provider';
  const peerProviderCapability = presentationOnly
    ? 'product_control_presentation_v1'
    : nativeProvider
      ? 'product_control_native_v1'
      : undefined;
  return {
    desktop,
    cli: availability(!presentationOnly && !nativeProvider, headlessReason),
    peer: peer(...(peerProviderCapability ? [peerProviderCapability] : [])),
    remoteControl: remote,
    detachedDispatch: availability(!presentationOnly && !nativeProvider, headlessReason),
  };
}

function outputSchema() {
  return { type: 'object', additionalProperties: true };
}

function itemIdsReferencing(capability, kind, id) {
  return capability.items
    .filter(({ control }) => control.kind === 'direct'
      && (kind === 'option'
        ? (control.options ?? []).some((option) => option.id === id)
        : (control.operations ?? []).includes(id)))
    .map((item) => item.id);
}

function buildResolvedDefinitions(capabilities) {
  const definitions = [];
  for (const capability of capabilities) {
    definitions.push({
      id: `${capability.id}:query`,
      capabilityId: capability.id,
      itemIds: capability.items.map(({ id }) => id),
      kind: 'query',
      risk: 'read',
      executionHost: 'productHost',
      availability: definitionAvailability('query'),
      inputSchema: { type: 'object', additionalProperties: false },
      outputSchema: outputSchema(),
      valueSource: { kind: 'static' },
      presentationTarget: capability.destination,
    });
    for (const option of capability.options) {
      const valueSource = option.handler.kind === 'appearanceSelection'
        ? { kind: 'appearanceCatalog' }
        : option.handler.kind === 'language'
          ? { kind: 'localeCatalog' }
          : option.handler.kind === 'provider'
            ? { kind: 'provider', providerId: option.handler.providerId }
            : { kind: 'static' };
      definitions.push({
        id: `${capability.id}:option:${option.id}`,
        capabilityId: capability.id,
        itemIds: itemIdsReferencing(capability, 'option', option.id),
        kind: 'option',
        risk: 'write',
        executionHost: 'productHost',
        availability: definitionAvailability('option', option.handler),
        inputSchema: option.valueSchema,
        outputSchema: outputSchema(),
        valueSource,
        presentationTarget: capability.destination,
      });
    }
    for (const operation of capability.operations) {
      definitions.push({
        id: `${capability.id}:operation:${operation.id}`,
        capabilityId: capability.id,
        itemIds: itemIdsReferencing(capability, 'operation', operation.id),
        kind: 'operation',
        risk: operation.risk,
        executionHost: operation.handler.kind === 'productAction'
          ? 'presentationSurface'
          : 'productHost',
        availability: definitionAvailability('operation', operation.handler),
        inputSchema: operation.inputSchema,
        outputSchema: outputSchema(),
        valueSource: operation.handler.kind === 'provider'
          ? { kind: 'provider', providerId: operation.handler.providerId }
          : { kind: 'static' },
        presentationTarget: operation.handler.kind === 'productAction'
          ? { kind: 'action', actionId: operation.handler.actionId }
          : capability.destination,
      });
    }
    for (const item of capability.items) {
      const target = item.destination ?? capability.destination;
      if (item.control.kind === 'delegate') {
        definitions.push({
          id: `${capability.id}:delegate:${item.id}`,
          capabilityId: capability.id,
          itemIds: [item.id],
          kind: 'delegate',
          risk: 'execute',
          executionHost: 'workspaceHost',
          availability: definitionAvailability('delegate'),
          inputSchema: { type: 'object', additionalProperties: true },
          outputSchema: outputSchema(),
          delegateTools: item.control.tools,
          presentationTarget: target,
        });
      } else if (item.control.kind === 'open') {
        definitions.push({
          id: `${capability.id}:open:${item.id}`,
          capabilityId: capability.id,
          itemIds: [item.id],
          kind: 'open',
          risk: 'ui',
          executionHost: 'presentationSurface',
          availability: definitionAvailability('open'),
          inputSchema: { type: 'object', additionalProperties: false },
          outputSchema: outputSchema(),
          openReason: item.control.reasonCode,
          presentationTarget: target,
        });
      }
    }
  }
  return definitions;
}

export function buildCapabilityCatalog() {
  const ownerDefinitions = loadOwnerDefinitions();
  const source = resolveOwnerFacts(JSON.parse(readFileSync(SOURCE_PATH, 'utf8')));
  const capabilityIds = validateSource(source);
  const interactionInventory = buildRequiredInteractionInventory();
  const technicalCoverage = buildTechnicalCoverage(source, capabilityIds);
  const technicalCommands = technicalCoverage.commands;
  validateDocumentationEvidence(source, technicalCommands);

  const runtimeCapabilities = source.capabilities.map((capability) => {
    const category = source.categories[capability.categoryId];
    return {
      ...capability,
      items: capability.items.map((item) => runtimeItem(item, capability)),
      operations: capability.operations ?? [],
      options: capability.options ?? [],
      searchTerms: searchTerms(capability, category),
      docsUrl: `${source.origin}/capabilities/${capability.id}/`,
    };
  });
  const publicCapabilities = runtimeCapabilities.map((capability) => ({
    ...capability,
    operations: capability.operations.map(publicOperation),
    options: capability.options.map(publicOption),
  }));
  const definitions = buildResolvedDefinitions(runtimeCapabilities);
  const ownerDigest = createHash('sha256')
    .update(JSON.stringify(ownerDefinitions))
    .digest('hex');
  const digest = createHash('sha256')
    .update(JSON.stringify({
      categories: source.categories,
      searchAcceptance: source.searchAcceptance,
      capabilities: publicCapabilities,
      definitions,
      ownerDefinitions,
    }))
    .digest('hex');
  const common = {
    schemaVersion: source.schemaVersion,
    product: source.product,
    title: source.title,
    origin: source.origin,
    source: toPosix(path.relative(REPO_ROOT, SOURCE_PATH)),
    digest,
    ownerDigest,
    searchAcceptance: source.searchAcceptance,
    counts: {
      features: publicCapabilities.filter(({ kind }) => kind === 'feature').length,
      settings: publicCapabilities.filter(({ kind }) => kind === 'setting').length,
      userFacing: publicCapabilities.length,
      documentedItems: publicCapabilities.reduce((total, capability) => total + capability.items.length, 0),
      controlCoverage: controlCoverage(source),
    },
    categories: source.categories,
    definitions,
  };
  const openEntries = source.capabilities.flatMap((capability) =>
    capability.items
      .filter(({ control }) => control.kind === 'open')
      .map((item) => ({
        capabilityId: capability.id,
        itemId: item.id,
        titleZh: item.titleZh,
        titleEn: item.titleEn,
        reasonCode: item.control.reasonCode,
        reasonZh: item.control.reasonZh,
        reasonEn: item.control.reasonEn,
        presentationTarget: item.destination ?? capability.destination,
        evidence: item.evidence,
      })),
  );
  const openReasonCounts = Object.fromEntries(
    [...new Set(openEntries.map(({ reasonCode }) => reasonCode))]
      .sort()
      .map((reasonCode) => [
        reasonCode,
        openEntries.filter((entry) => entry.reasonCode === reasonCode).length,
      ]),
  );
  return {
    publicCatalog: { ...common, capabilities: publicCapabilities },
    runtimeCatalog: { ...common, capabilities: runtimeCapabilities },
    technicalMap: {
      schemaVersion: 2,
      generatedFrom: toPosix(path.relative(REPO_ROOT, SOURCE_PATH)),
      catalogDigest: digest,
      commandCount: technicalCommands.length,
      coverage: technicalCoverage.coverage,
      commands: technicalCommands,
    },
    interactionAudit: {
      schemaVersion: 1,
      generatedFrom: toPosix(path.relative(REPO_ROOT, SOURCE_PATH)),
      catalogDigest: digest,
      ...interactionInventory,
    },
    openAudit: {
      schemaVersion: 1,
      generatedFrom: toPosix(path.relative(REPO_ROOT, SOURCE_PATH)),
      catalogDigest: digest,
      count: openEntries.length,
      reasonCounts: openReasonCounts,
      entries: openEntries,
    },
  };
}

