function buildTechnicalCoverage(source, capabilityIds) {
  const registrations = parseRegisteredCommands(readFileSync(DESKTOP_LIB, 'utf8'));
  const duplicateIds = registrations.map(({ id }) => id).filter((id, index, all) => all.indexOf(id) !== index);
  if (duplicateIds.length) throw new Error(`Duplicate registered commands: ${duplicateIds.join(', ')}`);
  const functions = collectTauriFunctions();
  const policies = remoteSurfaceTauriPolicies();
  const registeredSet = new Set(registrations.map(({ id }) => id));
  const missingPolicies = [...registeredSet].filter((id) => !policies.has(id));
  const extraPolicies = [...policies.keys()].filter((id) => !registeredSet.has(id));
  if (missingPolicies.length || extraPolicies.length) {
    throw new Error([
      missingPolicies.length
        ? `Commands missing a Product Operation Registry row (add an op(...) row in `
          + `src/crates/contracts/product-domains/src/remote_surface/table.rs): ${missingPolicies.join(', ')}`
        : '',
      extraPolicies.length
        ? `Registry rows marked tauri_command without a registered command: ${extraPolicies.join(', ')}`
        : '',
    ].filter(Boolean).join('\n'));
  }

  const documentedOwners = new Map();
  for (const capability of source.capabilities) {
    for (const item of capability.items) {
      for (const reference of item.evidence) {
        if (!reference.startsWith('command:')) continue;
        const commandId = reference.slice('command:'.length);
        const value = documentedOwners.get(commandId) ?? {
          capabilityIds: new Set(),
          documentedItemIds: new Set(),
        };
        value.capabilityIds.add(capability.id);
        value.documentedItemIds.add(`${capability.id}:${item.id}`);
        documentedOwners.set(commandId, value);
      }
    }
  }

  const commands = registrations.map(({ id, rustPath }) => {
    const resolved = resolveRegisteredFunction(id, rustPath, functions.get(id) ?? []);
    const moduleId = commandModule(resolved.sourceFile);
    const owner = source.implementationOwners[moduleId];
    if (!owner) throw new Error(`Tauri module ${moduleId} has no semantic owner`);
    if (owner.capabilityId !== null && !capabilityIds.has(owner.capabilityId)) {
      throw new Error(`Tauri module ${moduleId} targets unknown capability ${owner.capabilityId}`);
    }
    const documented = documentedOwners.get(id);
    const documentedCapabilityIds = documented
      ? [...documented.capabilityIds].sort()
      : [];
    const fallbackCapabilityIds = owner.capabilityId ? [owner.capabilityId] : [];
    const semanticCapabilityIds = documentedCapabilityIds.length
      ? documentedCapabilityIds
      : fallbackCapabilityIds;
    return {
      id,
      moduleId,
      capabilityId: semanticCapabilityIds.length === 1 ? semanticCapabilityIds[0] : null,
      capabilityIds: semanticCapabilityIds,
      documentedItemIds: documented ? [...documented.documentedItemIds].sort() : [],
      visibility: documented ? 'documented' : owner.capabilityId === null ? 'internal' : 'implementation',
      rustPath,
      sourceFile: resolved.sourceFile,
      signature: resolved.signature,
      remoteWorkspacePolicy: policies.get(id),
    };
  }).sort((left, right) => left.id.localeCompare(right.id));

  const actualModules = new Map();
  for (const command of commands) {
    const values = actualModules.get(command.moduleId) ?? [];
    values.push(command);
    actualModules.set(command.moduleId, values);
  }
  const staleOwners = Object.keys(source.implementationOwners).filter((moduleId) => !actualModules.has(moduleId));
  if (staleOwners.length) throw new Error(`Semantic owners without Tauri modules: ${staleOwners.join(', ')}`);
  const implementationCommandIds = commands
    .filter(({ visibility }) => visibility !== 'documented')
    .map(({ id }) => id)
    .sort();
  const reviewedImplementationIds = Object.values(source.implementationOnlyCommands ?? {})
    .flat();
  if (reviewedImplementationIds.some((id) => typeof id !== 'string' || !id.trim())) {
    throw new Error('implementationOnlyCommands groups may contain only non-empty command IDs');
  }
  if (new Set(reviewedImplementationIds).size !== reviewedImplementationIds.length) {
    throw new Error('implementationOnlyCommands may not classify the same command twice');
  }
  const sortedReviewedImplementationIds = [...reviewedImplementationIds].sort();
  if (JSON.stringify(sortedReviewedImplementationIds) !== JSON.stringify(implementationCommandIds)) {
    const reviewed = new Set(sortedReviewedImplementationIds);
    const measured = new Set(implementationCommandIds);
    const missing = implementationCommandIds.filter((id) => !reviewed.has(id));
    const stale = sortedReviewedImplementationIds.filter((id) => !measured.has(id));
    throw new Error([
      missing.length
        ? `Commands without manual evidence or an explicit implementation-only classification: ${missing.join(', ')}`
        : '',
      stale.length
        ? `implementationOnlyCommands entries now documented or removed: ${stale.join(', ')}`
        : '',
    ].filter(Boolean).join('\n'));
  }
  const measuredCoverage = {
    commandCount: commands.length,
    documentedCommandCount: commands.length - implementationCommandIds.length,
    implementationCommandCount: implementationCommandIds.length,
    implementationDigest: createHash('sha256')
      .update(implementationCommandIds.join('\n'))
      .digest('hex'),
  };
  return { commands, coverage: measuredCoverage };
}

function searchTerms(capability, category) {
  return [...new Set([
    capability.id,
    capability.titleZh,
    capability.titleEn,
    category.titleZh,
    category.titleEn,
    ...capability.keywordsZh,
    ...capability.keywordsEn,
    ...capability.highlightsZh,
    ...capability.highlightsEn,
    ...capability.items.flatMap((item) => [item.titleZh, item.titleEn]),
    ...capability.agentExamplesZh,
    ...capability.agentExamplesEn,
    ...(capability.agentControl?.workflowZh ?? []),
    ...(capability.agentControl?.workflowEn ?? []),
    ...(capability.agentControl?.tool ? [capability.agentControl.tool] : []),
    ...capability.items.flatMap((item) => item.control.kind === 'delegate'
      ? [
        ...(item.control.tools ?? []),
        ...(item.control.workflowZh ?? []),
        ...(item.control.workflowEn ?? []),
      ]
      : []),
  ])];
}

let cachedOwnerDefinitions;

function loadOwnerDefinitions() {
  if (cachedOwnerDefinitions) return cachedOwnerDefinitions;
  const result = spawnSync(
    'cargo',
    ['run', '--quiet', '-p', 'openbitfun-product-domains', '--bin', PRODUCT_CONTROL_OWNER_EXPORT],
    { cwd: REPO_ROOT, encoding: 'utf8', maxBuffer: 16 * 1024 * 1024, windowsHide: true },
  );
  if (result.status !== 0) {
    throw new Error([
      'Failed to export the compiled ProductControl owner registry.',
      result.stderr?.trim(),
    ].filter(Boolean).join('\n'));
  }
  try {
    cachedOwnerDefinitions = JSON.parse(result.stdout);
  } catch (error) {
    throw new Error(`Compiled ProductControl owner registry returned invalid JSON: ${error.message}`);
  }
  if (!Array.isArray(cachedOwnerDefinitions) || cachedOwnerDefinitions.length === 0) {
    throw new Error('Compiled ProductControl owner registry must not be empty');
  }
  return cachedOwnerDefinitions;
}

let cachedRemoteSurfaceRegistry;

/**
 * The compiled Product Operation Registry (`openbitfun_product_domains::remote_surface`).
 * It is the single owner of every command's remote-workspace stance, Peer Device
 * stance, and peer-host capability list; the desktop, CLI and Web UI derive their
 * tables from it, so this generator reads the same source instead of parsing
 * host code.
 */
export function loadRemoteSurfaceRegistry() {
  if (cachedRemoteSurfaceRegistry) return cachedRemoteSurfaceRegistry;
  const result = spawnSync(
    'cargo',
    ['run', '--quiet', '-p', 'openbitfun-product-domains', '--bin', REMOTE_SURFACE_EXPORT],
    { cwd: REPO_ROOT, encoding: 'utf8', maxBuffer: 16 * 1024 * 1024, windowsHide: true },
  );
  if (result.status !== 0) {
    throw new Error([
      'Failed to export the compiled Product Operation Registry.',
      result.stderr?.trim(),
    ].filter(Boolean).join('\n'));
  }
  let parsed;
  try {
    parsed = JSON.parse(result.stdout);
  } catch (error) {
    throw new Error(`Compiled Product Operation Registry returned invalid JSON: ${error.message}`);
  }
  if (!Array.isArray(parsed.operations) || parsed.operations.length === 0) {
    throw new Error('Compiled Product Operation Registry must not be empty');
  }
  if (typeof parsed.digest !== 'string' || !parsed.digest) {
    throw new Error('Compiled Product Operation Registry must carry a digest');
  }
  cachedRemoteSurfaceRegistry = { raw: result.stdout, registry: parsed };
  return cachedRemoteSurfaceRegistry;
}

