function toPosix(value) {
  return value.split(path.sep).join('/');
}

function walkFiles(root, predicate) {
  const results = [];
  if (!existsSync(root)) return results;
  for (const name of readdirSync(root)) {
    const absolute = path.join(root, name);
    const stat = statSync(absolute);
    if (stat.isDirectory()) results.push(...walkFiles(absolute, predicate));
    else if (predicate(absolute)) results.push(absolute);
  }
  return results;
}

function stripRustComments(source) {
  return source.replace(/\/\*[\s\S]*?\*\//gu, '').replace(/\/\/.*$/gmu, '');
}

export function parseRegisteredCommands(source) {
  const match = source.match(/\.invoke_handler\(tauri::generate_handler!\[([\s\S]*?)\]\)/u);
  if (!match) throw new Error('Desktop invoke_handler registration block was not found');
  const entries = stripRustComments(match[1])
    .split(',')
    .map((entry) => entry.trim())
    .filter(Boolean);
  const invalid = entries.filter((entry) => !/^[A-Za-z0-9_:]+$/u.test(entry));
  if (invalid.length) throw new Error(`Unsupported invoke_handler entries: ${invalid.join(', ')}`);
  return entries.map((rustPath) => ({ id: rustPath.split('::').at(-1), rustPath }));
}

function findBalancedFunctionEnd(source, start) {
  let parenDepth = 0;
  let angleDepth = 0;
  let bracketDepth = 0;
  let inString = false;
  let escaped = false;
  for (let index = start; index < source.length; index += 1) {
    const char = source[index];
    if (inString) {
      if (escaped) escaped = false;
      else if (char === '\\') escaped = true;
      else if (char === '"') inString = false;
      continue;
    }
    if (char === '"') inString = true;
    else if (char === '(') parenDepth += 1;
    else if (char === ')') parenDepth -= 1;
    else if (char === '<') angleDepth += 1;
    else if (char === '>') angleDepth = Math.max(0, angleDepth - 1);
    else if (char === '[') bracketDepth += 1;
    else if (char === ']') bracketDepth -= 1;
    else if (char === '{' && parenDepth === 0 && angleDepth === 0 && bracketDepth === 0) return index;
  }
  return -1;
}

function collectTauriFunctions() {
  const byName = new Map();
  const rustFiles = walkFiles(DESKTOP_ROOT, (file) => file.endsWith('.rs'));
  const marker = /#\[tauri::command(?:\([^\]]*\))?\]/gu;
  for (const file of rustFiles) {
    const source = readFileSync(file, 'utf8');
    for (const attribute of source.matchAll(marker)) {
      const tailStart = attribute.index + attribute[0].length;
      const tail = source.slice(tailStart);
      const fnMatch = tail.match(/^(?:\s*#\[[^\]]+\])*\s*(?:pub(?:\([^)]*\))?\s+)?(?:async\s+)?fn\s+([A-Za-z0-9_]+)\s*\(/u);
      if (!fnMatch) continue;
      const functionStart = tailStart + fnMatch.index + fnMatch[0].indexOf('fn ');
      const functionEnd = findBalancedFunctionEnd(source, functionStart);
      if (functionEnd < 0) throw new Error(`Could not parse command signature in ${file}`);
      const value = {
        name: fnMatch[1],
        sourceFile: toPosix(path.relative(REPO_ROOT, file)),
        signature: source.slice(functionStart, functionEnd).replace(/\s+/gu, ' ').trim(),
      };
      const existing = byName.get(value.name) ?? [];
      existing.push(value);
      byName.set(value.name, existing);
    }
  }
  return byName;
}

function normalizeConditionalSignature(signature) {
  return signature.replace(/\b_([a-z][a-z0-9_]*)\s*:/gu, '$1:');
}

function resolveRegisteredFunction(id, rustPath, allCandidates) {
  const moduleHint = rustPath.split('::').at(-2);
  const moduleCandidates = moduleHint
    ? allCandidates.filter(({ sourceFile }) => {
      const withoutExtension = sourceFile.replace(/\.rs$/u, '');
      return withoutExtension.endsWith(`/${moduleHint}`) || withoutExtension.includes(`/${moduleHint}/`);
    })
    : [];
  const candidates = moduleCandidates.length ? moduleCandidates : allCandidates;
  if (!candidates.length) throw new Error(`Registered command ${id} has no matching #[tauri::command] function`);
  const shapes = new Set(candidates.map(({ signature }) => normalizeConditionalSignature(signature)));
  if (shapes.size !== 1) throw new Error(`Registered command ${id} has incompatible conditional implementations`);
  return candidates.find(({ signature }) => !/\b_[a-z][a-z0-9_]*\s*:/u.test(signature)) ?? candidates[0];
}

function commandModule(sourceFile) {
  const basename = path.basename(sourceFile, '.rs');
  if (basename === 'commands' || basename === 'lib') return basename;
  return basename.replace(/_api$/u, '');
}

function extractSingleQuotedIds(source) {
  return new Set([...source.matchAll(/(?:id|actionId|sceneId):\s*'([^']+)'/gu)].map((match) => match[1]));
}

function extractTypeUnionIds(source, typeName) {
  const match = source.match(new RegExp(`export type ${typeName}\\s*=([\\s\\S]*?);`, 'u'));
  if (!match) throw new Error(`${typeName} union was not found`);
  return new Set([...match[1].matchAll(/'([^']+)'/gu)].map((value) => value[1]));
}

function extractProductToolNames(source) {
  const names = new Set();
  for (const match of source.matchAll(/tool_names:\s*&\[([\s\S]*?)\]/gu)) {
    for (const value of match[1].matchAll(/"([^"]+)"/gu)) names.add(value[1]);
  }
  return names;
}

function assertBilingual(capability, field) {
  const zh = capability[`${field}Zh`];
  const en = capability[`${field}En`];
  if (typeof zh !== 'string' || !/[\u3400-\u9fff]/u.test(zh)) {
    throw new Error(`${capability.id}.${field}Zh must contain Chinese text`);
  }
  if (typeof en !== 'string' || !/[A-Za-z]/u.test(en)) {
    throw new Error(`${capability.id}.${field}En must contain English text`);
  }
}

function buildInteractionInventory(roots) {
  const signature = [];
  const files = [];
  const interactionLine = /(?:<(?:button|input|select|textarea)\b|\b(?:type|role)=["'](?:button|checkbox|radio|search|menuitem|option|switch|tab)["']|\bon(?:Click|Change|Submit|Select|Press|DoubleClick|ContextMenu|KeyDown|Drop|DragEnd|Blur)=|<(?:Button|IconButton|Checkbox|Switch|Toggle|Select|MenuItem|DropdownMenuItem|Tabs?|Slider|Input|Textarea)\b|\b(?:definePage|registerProductAction)\s*\(|\b(?:actionId|sceneId|eventName)\s*:|startElementSelection|insert-context-tag)/u;
  for (const relativeRoot of roots) {
    const absoluteRoot = path.join(REPO_ROOT, ...relativeRoot.split('/'));
    if (!existsSync(absoluteRoot) || !statSync(absoluteRoot).isDirectory()) {
      throw new Error(`Reviewed interaction root does not exist: ${relativeRoot}`);
    }
    const sourceFiles = walkFiles(absoluteRoot, (file) => {
      const normalized = toPosix(file);
      return /\.(?:ts|tsx)$/u.test(file)
        && !/\.(?:test|spec|stories|example)\.(?:ts|tsx)$/u.test(file)
        && !normalized.includes('/__tests__/')
        && !normalized.includes('/generated/');
    })
      .map((file) => ({
        file,
        relativeFile: toPosix(path.relative(REPO_ROOT, file)),
      }))
      .sort((left, right) => left.relativeFile < right.relativeFile ? -1 : left.relativeFile > right.relativeFile ? 1 : 0);
    for (const { file, relativeFile } of sourceFiles) {
      const matchedLines = readFileSync(file, 'utf8')
        .split(/\r?\n/u)
        .map((line) => line.trim().replace(/\s+/gu, ' '))
        .filter((line) => interactionLine.test(line));
      if (!matchedLines.length) continue;
      signature.push(relativeFile, ...matchedLines);
      files.push({
        sourceFile: relativeFile,
        interactionCount: matchedLines.length,
        digest: createHash('sha256').update(matchedLines.join('\n')).digest('hex'),
      });
    }
  }
  return {
    roots,
    digest: createHash('sha256').update(signature.join('\n')).digest('hex'),
    fileCount: files.length,
    interactionCount: files.reduce((total, file) => total + file.interactionCount, 0),
    files,
  };
}

function buildRequiredInteractionInventory() {
  return buildInteractionInventory(REQUIRED_INTERACTION_ROOTS);
}

function validateValueSchema(schema, owner) {
  if (!schema || !['boolean', 'string', 'integer', 'number', 'object', 'array'].includes(schema.type)) {
    throw new Error(`${owner} needs a supported value schema`);
  }
  const supportedFields = new Set([
    'type', 'nullable', 'enum', 'minimum', 'maximum', 'minLength', 'maxLength',
  ]);
  const unsupported = Object.keys(schema).filter((field) => !supportedFields.has(field));
  if (unsupported.length) {
    throw new Error(`${owner}.valueSchema uses unsupported fields: ${unsupported.join(', ')}`);
  }
  if (schema.nullable !== undefined && typeof schema.nullable !== 'boolean') {
    throw new Error(`${owner}.valueSchema.nullable must be a boolean`);
  }
  for (const field of ['minimum', 'maximum']) {
    if (schema[field] !== undefined && (typeof schema[field] !== 'number' || !Number.isFinite(schema[field]))) {
      throw new Error(`${owner}.valueSchema.${field} must be a finite number`);
    }
  }
  if ((schema.minimum !== undefined || schema.maximum !== undefined)
      && !['integer', 'number'].includes(schema.type)) {
    throw new Error(`${owner}.valueSchema numeric bounds require an integer or number type`);
  }
  if (schema.type === 'integer'
      && [schema.minimum, schema.maximum].some((value) => value !== undefined && !Number.isInteger(value))) {
    throw new Error(`${owner}.valueSchema integer bounds must be integers`);
  }
  if (schema.minimum !== undefined && schema.maximum !== undefined && schema.minimum > schema.maximum) {
    throw new Error(`${owner}.valueSchema.minimum must not exceed maximum`);
  }
  for (const field of ['minLength', 'maxLength']) {
    if (schema[field] !== undefined && (!Number.isInteger(schema[field]) || schema[field] < 0)) {
      throw new Error(`${owner}.valueSchema.${field} must be a non-negative integer`);
    }
  }
  if ((schema.minLength !== undefined || schema.maxLength !== undefined) && schema.type !== 'string') {
    throw new Error(`${owner}.valueSchema string lengths require a string type`);
  }
  if (schema.minLength !== undefined && schema.maxLength !== undefined && schema.minLength > schema.maxLength) {
    throw new Error(`${owner}.valueSchema.minLength must not exceed maxLength`);
  }
  if (schema.enum !== undefined) {
    if (!Array.isArray(schema.enum) || schema.enum.length === 0) {
      throw new Error(`${owner}.valueSchema.enum must be a non-empty array`);
    }
    const serialized = schema.enum.map((value) => JSON.stringify(value));
    if (new Set(serialized).size !== serialized.length) {
      throw new Error(`${owner}.valueSchema.enum must not contain duplicate values`);
    }
    for (const value of schema.enum) validateStaticOptionValue(schema, value, owner);
  }
}

function validateOperationSchema(schema, owner, inheritedProperties = null) {
  if (!schema || typeof schema !== 'object' || Array.isArray(schema)) {
    throw new Error(`${owner} must be a JSON Schema object`);
  }
  const supportedFields = new Set([
    'type', 'enum', 'const', 'minimum', 'maximum', 'minLength', 'maxLength',
    'items', 'properties', 'required', 'additionalProperties', 'anyOf', 'description',
  ]);
  const unsupported = Object.keys(schema).filter((field) => !supportedFields.has(field));
  if (unsupported.length) {
    throw new Error(`${owner} uses unsupported input-schema fields: ${unsupported.join(', ')}`);
  }
  if (schema.type !== undefined
      && !['boolean', 'string', 'integer', 'number', 'object', 'array', 'null'].includes(schema.type)) {
    throw new Error(`${owner}.type is not supported by product control`);
  }
  for (const field of ['minimum', 'maximum']) {
    if (schema[field] !== undefined && (typeof schema[field] !== 'number' || !Number.isFinite(schema[field]))) {
      throw new Error(`${owner}.${field} must be a finite number`);
    }
  }
  if (schema.minimum !== undefined && schema.maximum !== undefined && schema.minimum > schema.maximum) {
    throw new Error(`${owner}.minimum must not exceed maximum`);
  }
  for (const field of ['minLength', 'maxLength']) {
    if (schema[field] !== undefined && (!Number.isInteger(schema[field]) || schema[field] < 0)) {
      throw new Error(`${owner}.${field} must be a non-negative integer`);
    }
  }
  if (schema.minLength !== undefined && schema.maxLength !== undefined && schema.minLength > schema.maxLength) {
    throw new Error(`${owner}.minLength must not exceed maxLength`);
  }
  if (schema.enum !== undefined && (!Array.isArray(schema.enum) || schema.enum.length === 0)) {
    throw new Error(`${owner}.enum must be a non-empty array`);
  }
  if (schema.additionalProperties !== undefined && typeof schema.additionalProperties !== 'boolean') {
    throw new Error(`${owner}.additionalProperties must be a boolean`);
  }
  if (schema.properties !== undefined
      && (!schema.properties || typeof schema.properties !== 'object' || Array.isArray(schema.properties))) {
    throw new Error(`${owner}.properties must be an object`);
  }
  const properties = schema.properties ?? inheritedProperties;
  for (const [property, propertySchema] of Object.entries(schema.properties ?? {})) {
    validateOperationSchema(propertySchema, `${owner}.properties.${property}`);
  }
  if (schema.required !== undefined) {
    if (!Array.isArray(schema.required)
        || schema.required.some((field) => typeof field !== 'string' || !field)) {
      throw new Error(`${owner}.required must contain non-empty property names`);
    }
    if (new Set(schema.required).size !== schema.required.length) {
      throw new Error(`${owner}.required must not contain duplicates`);
    }
    if (properties) {
      const missing = schema.required.filter((field) => !Object.hasOwn(properties, field));
      if (missing.length) throw new Error(`${owner} requires unknown arguments: ${missing.join(', ')}`);
    }
  }
  if (schema.items !== undefined) validateOperationSchema(schema.items, `${owner}.items`);
  if (schema.anyOf !== undefined) {
    if (!Array.isArray(schema.anyOf) || schema.anyOf.length === 0) {
      throw new Error(`${owner}.anyOf must be a non-empty array`);
    }
    schema.anyOf.forEach((alternative, index) => {
      validateOperationSchema(alternative, `${owner}.anyOf[${index}]`, properties);
    });
  }
}

function controlCoverage(source) {
  const coverage = { direct: 0, delegated: 0, interactive: 0, unsupported: 0 };
  for (const capability of source.capabilities) {
    for (const item of capability.items) {
      const kind = item.control.kind;
      if (kind === 'direct') coverage.direct += 1;
      else if (kind === 'delegate') coverage.delegated += 1;
      else if (kind === 'open') coverage.interactive += 1;
      else if (kind === 'unsupported') coverage.unsupported += 1;
    }
  }
  return coverage;
}

// Keep historical destinations on the wire for older presentation surfaces.
// Validate coverage against the same migration data used by the current Web UI.
export function projectSettingsCatalogDestination(capabilityId, destination, itemId) {
  if (destination.kind !== 'settings') return destination;
  const capability = SETTINGS_MIGRATIONS.capabilities[capabilityId];
  const input = capability?.items?.[itemId] ?? capability?.destination ?? destination;
  const migratedView = SETTINGS_MIGRATIONS.views[input.pageId]?.[input.viewId];
  const migrated = migratedView ?? SETTINGS_MIGRATIONS.pages[input.pageId];
  const sectionId = input.sectionId ?? migrated?.sectionId;
  return {
    kind: 'settings',
    pageId: migrated?.pageId ?? input.pageId,
    ...(sectionId ? { sectionId } : {}),
    ...(!migratedView && input.viewId ? { viewId: input.viewId } : {}),
  };
}

function validateSource(source) {
  if (source.schemaVersion !== 5) throw new Error('Interactive capability source must use schemaVersion 5');
  const capabilityIds = new Set();
  const settingsSource = readFileSync(SETTINGS_REGISTRY, 'utf8');
  const settingsIds = new Set(
    [...settingsSource.matchAll(/definePage\(\{\s*id:\s*'([^']+)'/gu)].map((match) => match[1]),
  );
  const settingsViewIds = extractTypeUnionIds(readFileSync(SETTINGS_TYPES, 'utf8'), 'SettingsViewId');
  const settingsSectionIds = extractTypeUnionIds(readFileSync(SETTINGS_TYPES, 'utf8'), 'SettingsSectionId');
  const actionIds = extractSingleQuotedIds(readFileSync(PRODUCT_ACTION_CATALOG, 'utf8'));
  const sceneIds = new Set([
    ...readFileSync(SCENE_TYPES, 'utf8').matchAll(/^\s*\|\s*'([^']+)'/gmu),
  ].map((match) => match[1]));
  const productToolNames = extractProductToolNames(readFileSync(TOOL_PROVIDER_GROUPS, 'utf8'));
  const delegatedToolNames = new Set();

  const validateDestination = (original, capabilityId, itemId) => {
    const owner = itemId ? `${capabilityId}.${itemId}` : capabilityId;
    const destination = projectSettingsCatalogDestination(capabilityId, original, itemId);
    if (destination.kind === 'settings') {
      if (!settingsIds.has(destination.pageId)) {
        throw new Error(`${owner} targets unknown settings page ${destination.pageId}`);
      }
      if (destination.viewId && !settingsViewIds.has(destination.viewId)) {
        throw new Error(`${owner} targets unknown settings view ${destination.viewId}`);
      }
      if (destination.sectionId && !settingsSectionIds.has(destination.sectionId)) {
        throw new Error(`${owner} targets unknown settings section ${destination.sectionId}`);
      }
      return;
    }
    if (destination.kind === 'action' && !actionIds.has(destination.actionId)) {
      throw new Error(`${owner} targets unknown product action ${destination.actionId}`);
    }
    if (destination.kind === 'scene' && !sceneIds.has(destination.sceneId)) {
      throw new Error(`${owner} targets unknown scene ${destination.sceneId}`);
    }
    if (destination.kind === 'event' && !/^openbitfun:[a-z0-9-]+$/u.test(destination.eventName)) {
      throw new Error(`${owner} has an invalid UI event destination`);
    }
    if (!['settings', 'action', 'scene', 'event'].includes(destination.kind)) {
      throw new Error(`${owner} has an unsupported destination`);
    }
  };

  for (const capability of source.capabilities) {
    if (!/^(feature|setting)\.[a-z0-9.-]+$/u.test(capability.id)) {
      throw new Error(`Invalid user-facing capability ID: ${capability.id}`);
    }
    if (capabilityIds.has(capability.id)) throw new Error(`Duplicate capability ID: ${capability.id}`);
    capabilityIds.add(capability.id);
    if (!['feature', 'setting'].includes(capability.kind)) throw new Error(`${capability.id} needs kind feature or setting`);
    if (!source.categories[capability.categoryId]) throw new Error(`${capability.id} has an unknown category`);
    for (const field of ['title', 'summary']) assertBilingual(capability, field);
    for (const field of ['keywordsZh', 'keywordsEn', 'highlightsZh', 'highlightsEn', 'stepsZh', 'stepsEn', 'agentExamplesZh', 'agentExamplesEn']) {
      if (!Array.isArray(capability[field]) || capability[field].length === 0) {
        throw new Error(`${capability.id}.${field} must be a non-empty array`);
      }
    }
    for (const field of ['highlights', 'steps', 'agentExamples']) {
      if (capability[`${field}Zh`].length !== capability[`${field}En`].length) {
        throw new Error(`${capability.id}.${field} must have matching Chinese and English entries`);
      }
    }
    if (capability.agentControl) {
      if (typeof capability.agentControl.tool !== 'string' || !capability.agentControl.tool.trim()) {
        throw new Error(`${capability.id}.agentControl.tool must name the controlling Agent tool`);
      }
      if (!productToolNames.has(capability.agentControl.tool)) {
        throw new Error(
          `${capability.id}.agentControl delegates to unknown Agent tool ${capability.agentControl.tool}`,
        );
      }
      for (const field of ['workflowZh', 'workflowEn']) {
        if (!Array.isArray(capability.agentControl[field]) || capability.agentControl[field].length === 0) {
          throw new Error(`${capability.id}.agentControl.${field} must be a non-empty array`);
        }
      }
      if (capability.agentControl.workflowZh.length !== capability.agentControl.workflowEn.length) {
        throw new Error(`${capability.id}.agentControl workflows must have matching Chinese and English entries`);
      }
    }
    if (!Array.isArray(capability.items) || capability.items.length === 0) {
      throw new Error(`${capability.id}.items must document its user-visible sub-capabilities`);
    }
    const itemIds = new Set();
    const itemControlReferences = [];
    for (const item of capability.items) {
      if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/u.test(item.id ?? '')) {
        throw new Error(`${capability.id} has an invalid documented item ID: ${item.id ?? '<missing>'}`);
      }
      if (itemIds.has(item.id)) throw new Error(`${capability.id} has duplicate documented item ${item.id}`);
      itemIds.add(item.id);
      assertBilingual({ ...item, id: `${capability.id}.${item.id}` }, 'title');
      if (item.destination) {
        validateDestination(item.destination, capability.id, item.id);
        if (
          item.destination.kind === 'settings'
          && capability.destination.kind === 'settings'
          && item.destination.pageId !== capability.destination.pageId
        ) {
          throw new Error(`${capability.id}.${item.id} must stay inside its owning settings page`);
        }
      }
      if (!Array.isArray(item.evidence) || item.evidence.length === 0) {
        throw new Error(`${capability.id}.${item.id}.evidence must not be empty`);
      }
      const control = item.control;
      if (!control || !['direct', 'delegate', 'open', 'unsupported'].includes(control.kind)) {
        throw new Error(`${capability.id}.${item.id}.control must explicitly classify Agent control`);
      }
      if (control.kind === 'direct') {
        const operations = control.operations ?? [];
        const options = control.options ?? [];
        if (!Array.isArray(operations) || !Array.isArray(options) || operations.length + options.length === 0) {
          throw new Error(`${capability.id}.${item.id}.control direct mapping must reference operations or options`);
        }
        itemControlReferences.push({ itemId: item.id, operations, options });
      } else if (control.kind === 'delegate') {
        const tools = control.tools ?? (capability.agentControl ? [capability.agentControl.tool] : []);
        const workflowZh = control.workflowZh ?? capability.agentControl?.workflowZh;
        const workflowEn = control.workflowEn ?? capability.agentControl?.workflowEn;
        if (!Array.isArray(tools) || tools.length === 0) {
          throw new Error(`${capability.id}.${item.id} delegates without an Agent tool binding`);
        }
        for (const tool of tools) {
          if (!productToolNames.has(tool)) {
            throw new Error(`${capability.id}.${item.id} delegates to unknown Agent tool ${tool}`);
          }
          delegatedToolNames.add(tool);
        }
        if (!Array.isArray(workflowZh) || !Array.isArray(workflowEn) || workflowZh.length === 0) {
          throw new Error(`${capability.id}.${item.id} needs a bilingual delegated workflow`);
        }
        if (workflowZh.length !== workflowEn.length) {
          throw new Error(`${capability.id}.${item.id} delegated workflows must have matching entries`);
        }
      } else {
        assertBilingual({ ...control, id: `${capability.id}.${item.id}.control` }, 'reason');
        if (control.kind === 'open' && ![
          'externalAuth',
          'secretEntry',
          'visualSelection',
          'unstructuredInteraction',
        ].includes(control.reasonCode)) {
          throw new Error(`${capability.id}.${item.id}.control needs a machine-checkable reasonCode`);
        }
      }
    }

    validateDestination(capability.destination, capability.id);

    const operationIds = new Set();
    for (const operation of capability.operations ?? []) {
      if (operationIds.has(operation.id)) throw new Error(`${capability.id} has duplicate operation ${operation.id}`);
      operationIds.add(operation.id);
      assertBilingual({ ...operation, id: `${capability.id}.${operation.id}` }, 'title');
      assertBilingual({ ...operation, id: `${capability.id}.${operation.id}` }, 'description');
      if (!operation.inputSchema || operation.inputSchema.type !== 'object') {
        throw new Error(`${capability.id}.${operation.id} needs an object input schema`);
      }
      if (operation.inputSchema.additionalProperties !== false) {
        throw new Error(`${capability.id}.${operation.id} must reject unknown operation arguments`);
      }
      validateOperationSchema(
        operation.inputSchema,
        `${capability.id}.${operation.id}.inputSchema`,
      );
      const operationProperties = operation.inputSchema.properties ?? {};
      if (operation.argumentScopes !== undefined) {
        if (!operation.argumentScopes
            || typeof operation.argumentScopes !== 'object'
            || Array.isArray(operation.argumentScopes)) {
          throw new Error(`${capability.id}.${operation.id}.argumentScopes must be an object`);
        }
        for (const [argument, scope] of Object.entries(operation.argumentScopes)) {
          if (!Object.hasOwn(operationProperties, argument)) {
            throw new Error(`${capability.id}.${operation.id} scopes unknown argument ${argument}`);
          }
          if (scope !== 'productHostLocal') {
            throw new Error(
              `${capability.id}.${operation.id}.${argument} has unsupported argument scope ${scope}`,
            );
          }
          if (operationProperties[argument]?.type !== 'string') {
            throw new Error(
              `${capability.id}.${operation.id}.${argument} product-host paths must be strings`,
            );
          }
        }
      }
      for (const required of operation.inputSchema.required ?? []) {
        if (!Object.hasOwn(operationProperties, required)) {
          throw new Error(`${capability.id}.${operation.id} requires unknown argument ${required}`);
        }
      }
      if (operation.handler.kind === 'productAction') {
        if (!actionIds.has(operation.handler.actionId)) {
          throw new Error(`${capability.id}.${operation.id} targets an unknown product action`);
        }
        if (Object.keys(operationProperties).length > 0) {
          throw new Error(`${capability.id}.${operation.id} product action cannot consume arguments`);
        }
      } else if (
        operation.handler.kind !== 'provider'
        || !/^[a-z0-9]+(?:-[a-z0-9]+)*$/u.test(operation.handler.providerId ?? '')
        || !/^[a-z0-9]+(?:-[a-z0-9]+)*$/u.test(operation.handler.operationId ?? '')
      ) {
        throw new Error(`${capability.id}.${operation.id} has an unsupported operation handler`);
      }
    }

    const optionIds = new Set();
    for (const option of capability.options ?? []) {
      if (capability.kind !== 'setting') throw new Error(`${capability.id} exposes options but is not a setting`);
      if (optionIds.has(option.id)) throw new Error(`${capability.id} has duplicate option ${option.id}`);
      optionIds.add(option.id);
      assertBilingual({ ...option, id: `${capability.id}.${option.id}` }, 'title');
      assertBilingual({ ...option, id: `${capability.id}.${option.id}` }, 'description');
      validateValueSchema(option.valueSchema, `${capability.id}.${option.id}`);
      if (option.handler.kind === 'config' && !option.handler.path) {
        throw new Error(`${capability.id}.${option.id} needs a config path`);
      }
      if (option.handler.kind === 'mergeConfig' && (!option.handler.path || !option.handler.fields?.length)) {
        throw new Error(`${capability.id}.${option.id} needs a merge path and fields`);
      }
      if (option.handler.kind === 'provider' && (
        !/^[a-z0-9]+(?:-[a-z0-9]+)*$/u.test(option.handler.providerId ?? '')
        || !/^[a-z0-9]+(?:-[a-z0-9]+)*$/u.test(option.handler.optionId ?? '')
      )) {
        throw new Error(`${capability.id}.${option.id} has an invalid provider option handler`);
      }
      if (![
        'config',
        'mergeConfig',
        'appearanceSelection',
        'language',
        'flowChatPermissionModeControl',
        'provider',
      ].includes(option.handler.kind)) {
        throw new Error(`${capability.id}.${option.id} has an unsupported option handler`);
      }
    }

    const referencedOperationIds = new Set();
    const referencedOptionIds = new Set();
    for (const reference of itemControlReferences) {
      for (const operationId of reference.operations) {
        if (!operationIds.has(operationId)) {
          throw new Error(`${capability.id}.${reference.itemId} controls unknown operation ${operationId}`);
        }
        referencedOperationIds.add(operationId);
      }
      for (const option of reference.options) {
        if (!option || typeof option.id !== 'string' || !optionIds.has(option.id)) {
          throw new Error(`${capability.id}.${reference.itemId} controls an unknown option`);
        }
        referencedOptionIds.add(option.id);
        if (Object.hasOwn(option, 'value')) {
          const contract = (capability.options ?? []).find(({ id }) => id === option.id);
          validateStaticOptionValue(contract.valueSchema, option.value, `${capability.id}.${reference.itemId}`);
        }
      }
    }
    const orphanOperations = [...operationIds].filter((id) => !referencedOperationIds.has(id));
    const orphanOptions = [...optionIds].filter((id) => !referencedOptionIds.has(id));
    if (orphanOperations.length || orphanOptions.length) {
      throw new Error([
        orphanOperations.length ? `${capability.id} has operations without documented-item control mapping: ${orphanOperations.join(', ')}` : '',
        orphanOptions.length ? `${capability.id} has options without documented-item control mapping: ${orphanOptions.join(', ')}` : '',
      ].filter(Boolean).join('\n'));
    }
  }

  const excludedAgentTools = source.agentToolExclusions;
  if (!Array.isArray(excludedAgentTools)) {
    throw new Error('agentToolExclusions must classify framework-only product tools');
  }
  const excludedAgentToolNames = new Set();
  for (const exclusion of excludedAgentTools) {
    if (!exclusion || typeof exclusion.tool !== 'string' || !exclusion.tool.trim()) {
      throw new Error('Every reviewed Agent-tool exclusion must name a tool');
    }
    if (excludedAgentToolNames.has(exclusion.tool)) {
      throw new Error(`Duplicate reviewed Agent-tool exclusion: ${exclusion.tool}`);
    }
    excludedAgentToolNames.add(exclusion.tool);
    assertBilingual({ ...exclusion, id: `agentToolExclusions.${exclusion.tool}` }, 'reason');
  }
  const staleAgentToolExclusions = [...excludedAgentToolNames]
    .filter((tool) => !productToolNames.has(tool));
  const overlappingAgentToolExclusions = [...excludedAgentToolNames]
    .filter((tool) => delegatedToolNames.has(tool));
  const uncoveredAgentTools = [...productToolNames]
    .filter((tool) => !delegatedToolNames.has(tool) && !excludedAgentToolNames.has(tool));
  if (staleAgentToolExclusions.length
      || overlappingAgentToolExclusions.length
      || uncoveredAgentTools.length) {
    throw new Error([
      staleAgentToolExclusions.length
        ? `Reviewed Agent-tool exclusions no longer exist: ${staleAgentToolExclusions.join(', ')}`
        : '',
      overlappingAgentToolExclusions.length
        ? `Agent tools cannot be both delegated and excluded: ${overlappingAgentToolExclusions.join(', ')}`
        : '',
      uncoveredAgentTools.length
        ? `Product Agent tools missing a user-capability mapping or reviewed framework exclusion: ${uncoveredAgentTools.join(', ')}`
        : '',
    ].filter(Boolean).join('\n'));
  }

  const measuredControlCoverage = controlCoverage(source);
  if (measuredControlCoverage.unsupported > 0) {
    throw new Error('User-facing capabilities may not silently ship as unsupported Agent controls');
  }

  const projectedSettingsDestinations = source.capabilities
    .filter(({ kind }) => kind === 'setting')
    .flatMap((capability) => [
      projectSettingsCatalogDestination(capability.id, capability.destination),
      ...capability.items.map((item) => projectSettingsCatalogDestination(
        capability.id, item.destination ?? capability.destination, item.id,
      )),
    ]);
  const semanticSettings = new Set(projectedSettingsDestinations
    .map((destination) => destination.kind === 'settings' ? destination.pageId : null)
    .filter(Boolean));
  const missingSettings = [...settingsIds].filter((id) => !semanticSettings.has(id));
  const staleSettings = [...semanticSettings].filter((id) => !settingsIds.has(id));
  if (missingSettings.length || staleSettings.length) {
    throw new Error([
      missingSettings.length ? `Settings pages missing from the semantic manual: ${missingSettings.join(', ')}` : '',
      staleSettings.length ? `Semantic settings without a registered page: ${staleSettings.join(', ')}` : '',
    ].filter(Boolean).join('\n'));
  }

  const semanticSettingsViews = new Set(projectedSettingsDestinations
    .map((destination) => destination.kind === 'settings' ? destination.viewId : null)
    .filter(Boolean));
  const missingSettingsViews = [...settingsViewIds].filter((id) => !semanticSettingsViews.has(id));
  const staleSettingsViews = [...semanticSettingsViews].filter((id) => !settingsViewIds.has(id));
  if (missingSettingsViews.length || staleSettingsViews.length) {
    throw new Error([
      missingSettingsViews.length
        ? `Settings views missing direct semantic destinations: ${missingSettingsViews.join(', ')}`
        : '',
      staleSettingsViews.length
        ? `Semantic destinations without registered settings views: ${staleSettingsViews.join(', ')}`
        : '',
    ].filter(Boolean).join('\n'));
  }

  for (const [label, owners, actual] of [
    ['product action', source.productActionOwners, actionIds],
    ['scene', source.sceneOwners, sceneIds],
  ]) {
    const ownerIds = new Set(Object.keys(owners ?? {}));
    const missing = [...actual].filter((id) => !ownerIds.has(id));
    const stale = [...ownerIds].filter((id) => !actual.has(id));
    if (missing.length || stale.length) {
      throw new Error([
        missing.length ? `${label}s missing semantic owners: ${missing.join(', ')}` : '',
        stale.length ? `Semantic ${label} owners without registry entries: ${stale.join(', ')}` : '',
      ].filter(Boolean).join('\n'));
    }
    for (const [id, capabilityId] of Object.entries(owners)) {
      if (!capabilityIds.has(capabilityId)) {
        throw new Error(`${label} ${id} targets unknown capability ${capabilityId}`);
      }
    }
  }
  if (!Array.isArray(source.searchAcceptance) || source.searchAcceptance.length === 0) {
    throw new Error('searchAcceptance must contain reviewed cross-surface search fixtures');
  }
  const acceptanceIds = new Set();
  const capabilityById = new Map(source.capabilities.map((capability) => [capability.id, capability]));
  for (const acceptance of source.searchAcceptance) {
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/u.test(acceptance.id ?? '')) {
      throw new Error(`Invalid search acceptance id: ${acceptance.id ?? '<missing>'}`);
    }
    if (acceptanceIds.has(acceptance.id)) throw new Error(`Duplicate search acceptance id: ${acceptance.id}`);
    acceptanceIds.add(acceptance.id);
    if (typeof acceptance.query !== 'string' || !acceptance.query.trim()) {
      throw new Error(`${acceptance.id} needs a non-empty search query`);
    }
    if (!Array.isArray(acceptance.expectedCapabilityIds) || acceptance.expectedCapabilityIds.length === 0) {
      throw new Error(`${acceptance.id} needs expectedCapabilityIds`);
    }
    for (const capabilityId of acceptance.expectedCapabilityIds) {
      if (!capabilityIds.has(capabilityId)) {
        throw new Error(`${acceptance.id} expects unknown capability ${capabilityId}`);
      }
    }
    if (!acceptance.expectedCapabilityIds.includes(acceptance.expectedFirstCapabilityId)) {
      throw new Error(`${acceptance.id}.expectedFirstCapabilityId must be an expected capability`);
    }
    if (acceptance.expectedItem) {
      const capability = capabilityById.get(acceptance.expectedItem.capabilityId);
      if (!capability || !capability.items.some(({ id }) => id === acceptance.expectedItem.itemId)) {
        throw new Error(`${acceptance.id} expects an unknown documented item`);
      }
      if (!acceptance.expectedCapabilityIds.includes(acceptance.expectedItem.capabilityId)) {
        throw new Error(`${acceptance.id}.expectedItem must belong to an expected capability`);
      }
    }
  }
  return capabilityIds;
}

function validateStaticOptionValue(schema, value, owner) {
  if (value === null && schema.nullable === true) return;
  const matches = schema.type === 'boolean' ? typeof value === 'boolean'
    : schema.type === 'string' ? typeof value === 'string'
      : schema.type === 'integer' ? Number.isInteger(value)
        : schema.type === 'number' ? typeof value === 'number' && Number.isFinite(value)
          : schema.type === 'object' ? value !== null && typeof value === 'object' && !Array.isArray(value)
            : schema.type === 'array' ? Array.isArray(value)
              : false;
  if (!matches) throw new Error(`${owner} has a static option value with the wrong type`);
  if (schema.enum && !schema.enum.some((candidate) => JSON.stringify(candidate) === JSON.stringify(value))) {
    throw new Error(`${owner} has a static option value outside its enum`);
  }
  if (typeof value === 'number' && schema.minimum !== undefined && value < schema.minimum) {
    throw new Error(`${owner} has a static option value below minimum`);
  }
  if (typeof value === 'number' && schema.maximum !== undefined && value > schema.maximum) {
    throw new Error(`${owner} has a static option value above maximum`);
  }
  if (typeof value === 'string' && schema.minLength !== undefined && [...value].length < schema.minLength) {
    throw new Error(`${owner} has a static option value shorter than minLength`);
  }
  if (typeof value === 'string' && schema.maxLength !== undefined && [...value].length > schema.maxLength) {
    throw new Error(`${owner} has a static option value longer than maxLength`);
  }
}

function parseSourceEvidence(reference, owner) {
  const separator = reference.indexOf('#');
  if (separator <= 'source:'.length || separator === reference.length - 1) {
    throw new Error(`${owner} has invalid source evidence: ${reference}`);
  }
  const relativePath = reference.slice('source:'.length, separator);
  const marker = reference.slice(separator + 1);
  if (relativePath.includes('..') || !/^(?:src|docs)\//u.test(relativePath)) {
    throw new Error(`${owner} source evidence must stay inside src/ or docs/: ${relativePath}`);
  }
  const absolutePath = path.join(REPO_ROOT, ...relativePath.split('/'));
  if (!existsSync(absolutePath) || !statSync(absolutePath).isFile()) {
    throw new Error(`${owner} source evidence file does not exist: ${relativePath}`);
  }
  const source = readFileSync(absolutePath, 'utf8');
  let markerExists = source.includes(marker);
  if (!markerExists && relativePath.endsWith('.json')) {
    try {
      let value = JSON.parse(source);
      for (const segment of marker.split('.')) {
        if (!value || typeof value !== 'object' || !Object.hasOwn(value, segment)) {
          value = undefined;
          break;
        }
        value = value[segment];
      }
      markerExists = value !== undefined;
    } catch {}
  }
  if (!markerExists) {
    throw new Error(`${owner} source evidence marker is missing from ${relativePath}: ${marker}`);
  }
}

function validateDocumentationEvidence(source, technicalCommands) {
  const commandIds = new Set(technicalCommands.map(({ id }) => id));
  for (const capability of source.capabilities) {
    capability.items.forEach((item) => {
      const owner = `${capability.id}.${item.id}`;
      const references = item.evidence;
      for (const reference of references) {
        if (typeof reference !== 'string') throw new Error(`${owner} references must be strings`);
        if (reference.startsWith('command:')) {
          const commandId = reference.slice('command:'.length);
          if (!commandIds.has(commandId)) throw new Error(`${owner} references unknown command ${commandId}`);
        } else if (reference.startsWith('source:')) {
          parseSourceEvidence(reference, owner);
        } else {
          throw new Error(`${owner} has unsupported evidence: ${reference}`);
        }
      }
    });
  }
}

